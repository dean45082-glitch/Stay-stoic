  const asEntry = (author,entry) => ({author,...entry});

  // Interleave one entry from each Stoic before inserting selected classical readings.
  const classical = [];
  bank.machiavelli.forEach((entry,index)=>{
    if (index < bank.caesar.length) classical.push(asEntry('caesar', bank.caesar[index]));
    classical.push(asEntry('machiavelli',entry));
  });
  const queue = [];
  for (let index=0; index<bank.marcus.length; index++) {
    for (const author of stoics) queue.push(asEntry(author,bank[author][index]));
    const next = Math.floor((index+1)*classical.length/bank.marcus.length);
    const previous = Math.floor(index*classical.length/bank.marcus.length);
    if (next>previous) queue.push(classical[previous]);
  }

  const classicalPortraits = {caesar:'julius-caesar.webp',machiavelli:'machiavelli.webp'};

  function QuoteFace({item,defaultPortrait}) {
    const h = w.React.createElement;
    const [language,setLanguage] = w.React.useState('es');
    const [flipped,setFlipped] = w.React.useState(false);
    const portrait = classicalPortraits[item.author] || defaultPortrait.portrait;
    const face = classicalPortraits[item.author] ? item.author : defaultPortrait.author;
    const reference = item.source ?
      item.source + (item.adaptation ? ' · Pasaje adaptado' : ' · Traducción') :
      'Adaptación inspirada en su pensamiento';

    return h('article',{
      className:'stoic-moment',
      'data-quote-author':item.author,
      'data-portrait-author':face
    },
      h('div',{className:'stoic-moment-copy'},
        h('div',{className:'stoic-moment-heading'},stoics.includes(item.author)?'Momento estoico':'Lectura clásica'),
        h('div',{'aria-live':'polite','aria-atomic':true},
          h('blockquote',{key:language,lang:language,className:flipped?'stoic-flip-face':undefined},
            '“'+item[language]+'”')
        ),
        h('div',{className:'stoic-moment-author'},authors[item.author]),
        h('div',{className:'stoic-moment-reference'},reference),
        h('button',{
          type:'button',
          className:'stoic-flip-button',
          onClick:()=>{setFlipped(true);setLanguage(previous=>previous==='es'?'en':'es')}
        },language==='es'?'↻ Ver en inglés':'↻ Ver en español')
      ),
      h('img',{src:portrait,alt:'Busto de '+authors[face],className:'stoic-moment-bust'})
    );
  }

  w.StayStoicMoment = function StayStoicMoment({day,moduleId}) {
    const defaultPortrait = modules[moduleId];
    const index = ((Math.max(1,Number(day)||1)-1)+defaultPortrait.start)%queue.length;
    return w.React.createElement(QuoteFace,{key:moduleId+':'+day,item:queue[index],defaultPortrait});
  };
